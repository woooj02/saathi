export function t(lang, key, vars = {}) {
  let s = (TEXT[lang] && TEXT[lang][key]) ?? TEXT.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, lang === "ne" ? toNe(v) : v);
  return s;
}
